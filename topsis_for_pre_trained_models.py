"""## Apply TOPSIS Method and Rank Models

### Subtask:
Implement the TOPSIS (Technique for Order Preference by Similarity to Ideal Solution) method to rank the evaluated models based on their performance metrics. This involves normalizing the decision matrix, applying weights to each criterion, determining the Positive Ideal Solution (PIS) and Negative Ideal Solution (NIS), calculating separation measures, computing TOPSIS scores for each model, and finally ranking the models.

**Reasoning**:
The first step is to define the weights for each criterion, create the `topsis_matrix` by selecting only the numerical columns from `decision_matrix`, and then normalize this matrix using vector normalization as per the instructions.
"""

import numpy as np

# 1. Define weights for each criterion (example: equal weights)
weights = {
    'Accuracy': 0.2,
    'Macro F1 Score': 0.2,
    'Inference Time Per Sample (s)': 0.2,
    'Model Size (MB)': 0.2,
    'Computational Cost': 0.2
}

# Ensure weights sum to 1 (optional check)
if abs(sum(weights.values()) - 1.0) > 1e-9:
    print("Warning: Weights do not sum to 1. Normalizing weights...")
    total_weight = sum(weights.values())
    weights = {k: v / total_weight for k, v in weights.items()}

# 2. Create a copy of the decision_matrix and remove 'Model Name' column
topsis_matrix = decision_matrix.drop(columns=['Model Name']).copy()

# 3. Normalize the topsis_matrix using vector normalization
# For each column (criterion), divide each value by the square root of the sum of the squares of all values in that column.
normalized_matrix = topsis_matrix.copy()
for col in topsis_matrix.columns:
    normalized_matrix[col] = topsis_matrix[col] / np.sqrt(np.sum(topsis_matrix[col]**2))

print("Weights:")
print(weights)
print("\nTOPSIS Matrix (numerical columns only):")
display(topsis_matrix)
print("\nNormalized Matrix:")
display(normalized_matrix)

"""**Reasoning**:
Now that the `normalized_matrix` has been created, I will apply the defined `weights` to it. This involves multiplying each column of the `normalized_matrix` by its corresponding weight as specified in the `weights` dictionary, creating the `weighted_normalized_matrix`.


"""

import pandas as pd

# 4. Apply the defined weights to the normalized_matrix
weighted_normalized_matrix = normalized_matrix.copy()
for col, weight in weights.items():
    if col in weighted_normalized_matrix.columns:
        weighted_normalized_matrix[col] = normalized_matrix[col] * weight

print("\nWeighted Normalized Matrix:")
display(weighted_normalized_matrix)

"""**Reasoning**:
I will determine the Positive Ideal Solution (PIS) and Negative Ideal Solution (NIS) for each criterion based on whether it is a 'benefit' or 'cost' as defined in `criteria_type`. For benefit criteria, PIS is the maximum value and NIS is the minimum. For cost criteria, PIS is the minimum value and NIS is the maximum. These will be stored as `pis` and `nis` (pandas Series).


"""

import pandas as pd

# 5. Determine the Positive Ideal Solution (PIS) and Negative Ideal Solution (NIS)
pis = pd.Series(index=weighted_normalized_matrix.columns, dtype=float)
nis = pd.Series(index=weighted_normalized_matrix.columns, dtype=float)

for col in weighted_normalized_matrix.columns:
    if col in criteria_type:
        if criteria_type[col] == 'benefit':
            pis[col] = weighted_normalized_matrix[col].max()
            nis[col] = weighted_normalized_matrix[col].min()
        elif criteria_type[col] == 'cost':
            pis[col] = weighted_normalized_matrix[col].min()
            nis[col] = weighted_normalized_matrix[col].max()
    else:
        # Handle cases where a column might not be in criteria_type if necessary
        # For this specific task, all columns in weighted_normalized_matrix are in criteria_type
        pass

print("\nPositive Ideal Solution (PIS):")
print(pis)
print("\nNegative Ideal Solution (NIS):")
print(nis)

"""**Reasoning**:
I will calculate the Euclidean distance of each model from the Positive Ideal Solution (PIS) and Negative Ideal Solution (NIS). This will create two new Series, `separation_from_pis` and `separation_from_nis`.


"""

import numpy as np

# 6. Calculate the separation of each model from the PIS (separation_from_pis) and NIS (separation_from_nis)
# This is done by computing the Euclidean distance between each row of the weighted_normalized_matrix
# and the pis/nis vectors.

# For PIS
separation_from_pis = np.sqrt(np.sum((weighted_normalized_matrix - pis)**2, axis=1))

# For NIS
separation_from_nis = np.sqrt(np.sum((weighted_normalized_matrix - nis)**2, axis=1))

print("\nSeparation from PIS:")
print(separation_from_pis)
print("\nSeparation from NIS:")
print(separation_from_nis)

"""**Reasoning**:
Now that the separation distances from PIS and NIS have been calculated, I will compute the TOPSIS score (Closeness Coefficient) for each model using the specified formula and add it as a new column to the `decision_matrix`.


"""

import pandas as pd

# 7. Calculate the TOPSIS score (Closeness Coefficient) for each model
topsis_score = separation_from_nis / (separation_from_pis + separation_from_nis)

# Add the TOPSIS score to the decision_matrix
